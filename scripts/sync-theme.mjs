import { readFileSync, writeFileSync } from "node:fs";
const root = new URL("../", import.meta.url);
const tokens = JSON.parse(readFileSync(new URL("packages/shared/src/tokens.json", root), "utf8"));
const lines = Object.entries(tokens.colors).map(([key, value]) => `  --${key}: ${value};`);
for (const [key, value] of Object.entries(tokens.radius)) lines.push(`  --tirkha-radius-${key}: ${value}px;`);
const css = "/* Generated by scripts/sync-theme.mjs. Edit tokens.json instead. */\n:root {\n" + lines.join("\n") + "\n}\n";
const target = new URL("packages/shared/src/theme.css", root);
if (process.argv.includes("--check")) {
  if (readFileSync(target, "utf8") !== css) throw new Error("Theme is stale. Run pnpm theme:sync.");
} else writeFileSync(target, css);
